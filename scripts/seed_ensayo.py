"""Load one isolated rehearsal/demo operation into DynamoDB, only creating absent rows. Owner: Rol 2.

    python scripts/ensayo_kit.py --run 7 --out ensayo-0007
    python scripts/seed_ensayo.py ensayo-0007                 # dry run: WOULD_CREATE / SAME / CONFLICT
    python scripts/seed_ensayo.py ensayo-0007 --apply         # create the operation's rows
    python scripts/seed_ensayo.py ensayo-0007 --apply --with-stock   # + 1 bearing in the run's warehouse (case 2)
    python scripts/seed_grants.py ensayo-0007/grants-participantes.json   # after filling in each Google `sub`

Never touches SSM, never overwrites a row (exit code 1 if a row exists with other content). Rows of the run:
OP#{op} / META, ZONE#, WH#, INCIDENT_SETTINGS; MACHINE#/PROFILE; TECH#/PROFILE; operator grant; optional stock.
The web shows the run with VITE_OPERATION_ID={op}.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "shared"))

from conditional_seed import print_report, put_new  # noqa: E402

ROWS = [
    "item-op-meta.json",
    "item-op-zone.json",
    "item-op-warehouse.json",
    "item-op-settings.json",
    "item-machine.json",
    "item-technician.json",
    "item-grant-operador.json",
]


def load_items(kit: Path, with_stock: bool = False) -> list[dict[str, Any]]:
    from boto3.dynamodb.types import TypeDeserializer

    de = TypeDeserializer()
    names = ROWS + (["item-stock-caso2.json"] if with_stock else [])
    items = []
    for name in names:
        typed = json.loads((kit / name).read_text(encoding="utf-8"))
        items.append({k: de.deserialize(v) for k, v in typed.items()})
    return items


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("kit", help="folder generated by scripts/ensayo_kit.py")
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--with-stock", action="store_true")
    args = parser.parse_args()

    from af_shared.ddb import get_table

    items = load_items(Path(args.kit), args.with_stock)
    return print_report(put_new(get_table(), items, apply=args.apply))


if __name__ == "__main__":
    sys.exit(main())
